#!/usr/bin/env node
// Development-only asset generation. Read package data, never upstream executable code.
import { readFile, readdir, writeFile, mkdir, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const upstream = dirname(require.resolve("material-icon-theme/package.json"));
const { version } = JSON.parse(await readFile(join(upstream, "package.json"), "utf8"));
const target = fileURLToPath(new URL("../src/client/src/plugins/themes/material/", import.meta.url));
const manifest = JSON.parse(await readFile(join(upstream, "dist/material-icons.json"), "utf8"));
const mit = await readFile(join(upstream, "LICENSE"), "utf8");
const apache = await readFile(join(target, "LICENSE-APACHE-2.0.txt"), "utf8");
const notice = await readFile(join(target, "NOTICE.txt"), "utf8");
const groups = new Map();
const used = new Set([manifest.file]);
for (const [field, property] of [["fileNames", "filenames"], ["fileExtensions", "extensions"]]) {
  for (const [matcher, icon] of Object.entries(manifest[field])) {
    // The host deliberately rejects path-based filename rules. Light variants
    // are unnecessary: consumers use these extension-specific shapes as masks.
    if (/[\\/]/u.test(matcher)) continue;
    used.add(icon);
    if (!groups.has(icon)) groups.set(icon, { icon, filenames: [], extensions: [] });
    groups.get(icon)[property].push(property === "extensions" ? `.${matcher}` : matcher);
  }
}
const assetDir = join(target, "icons");
// Leave unchanged files alone: routine tests/typechecks must not invalidate a
// running Vite graph or briefly remove assets being served by the dev client.
await mkdir(assetDir, { recursive: true });
const ids = [...used].sort();
for (const id of ids) {
  const filename = basename(manifest.iconDefinitions[id].iconPath);
  if (!/^[\w.-]+\.svg$/u.test(filename) || !/^[\w-]+$/u.test(id)) throw new Error(`Unexpected icon path: ${id}`);
  const svg = await readFile(join(upstream, "icons", filename), "utf8");
  if (/<script\b|<foreignObject\b|\bon\w+\s*=|(?:href|src)\s*=\s*["'](?!#)/iu.test(svg)) throw new Error(`Non-static SVG: ${id}`);
  const attribution = id === manifest.file
    ? `${notice}\n${mit}\n${apache}`
    : `Material Icon Theme ${version}. Copyright (c) 2025 Material Extensions. MIT. Source collections: Google Material Symbols / Pictogrammers (Apache-2.0; third-party exceptions). Full notices and licenses embedded in the bundled file.svg. Modified only to add this metadata.`;
  const escaped = attribution.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
  await writeIfChanged(join(assetDir, `${id}.svg`), svg.replace(/<svg\b[^>]*>/u, (root) => `${root}<metadata>${escaped}</metadata>`));
}
const expectedAssets = new Set(ids.map((id) => `${id}.svg`));
for (const filename of await readdir(assetDir)) {
  if (!expectedAssets.has(filename)) await rm(join(assetDir, filename), { force: true });
}
// Literal new URL expressions let Vite discover each asset; ?no-inline keeps
// even tiny SVGs out of JavaScript/data URLs and makes deployment URLs local.
const declarations = ids.map((id, index) => `const icon${index} = new URL("./icons/${id}.svg?no-inline", import.meta.url).href;`);
const asset = (id) => `{ url: icon${ids.indexOf(id)} }`;
const rules = [...groups.values()].map(({ icon, filenames, extensions }) => `    { ${[
  ...(filenames.length ? [`filenames: ${JSON.stringify(filenames)}`] : []),
  ...(extensions.length ? [`extensions: ${JSON.stringify(extensions)}`] : []),
  `icon: ${asset(icon)}`,
].join(", ")} },`);
await writeIfChanged(join(target, "generated.ts"), `// Generated by scripts/import-material-file-icons.mjs from material-icon-theme ${version}.\n// See NOTICE.txt. Do not edit; default qualification is owned by the host: themes:material.\nimport type { FileIconThemeContribution } from "../../types";\n\n${declarations.join("\n")}\n\nexport const materialFileIcons = {\n  file: ${asset(manifest.file)},\n  files: [\n${rules.join("\n")}\n  ],\n} satisfies Pick<FileIconThemeContribution, "file" | "files">;\n`);
console.log(`Generated ${ids.length} SVGs and ${groups.size} rules from installed material-icon-theme ${version}`);

async function writeIfChanged(path, content) {
  let previous;
  try { previous = await readFile(path, "utf8"); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  if (previous !== content) await writeFile(path, content);
}
